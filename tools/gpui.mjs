// Går igenom Grand Prix-läget med tangentbordet: meny → stall → enstaka GP → kval → lopp → resultat → säsong.
// node tools/gpui.mjs [bredd] [höjd]   (spelarens bil körs av datorn under kval och lopp)
import { createRequire } from 'module';
const require = createRequire('D:/Qisy/QISYFrontend/QISYFrontend-1/package.json');
const { chromium } = require('playwright');
const [,, w = '1440', h = '810'] = process.argv;
const PORT = process.env.PORT || '8803';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 3).join('\n')));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(`http://localhost:${PORT}/index.html?fast=4`);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.KK && window.KK.G.state === 'title', null, { timeout: 60000 });
await page.waitForTimeout(1500);
let n = 0;
const shot = async (name) => { await page.screenshot({ path: `tools/out/gpui-${String(n++).padStart(2, '0')}-${name}.png` }); };
const key = async (k, times = 1) => { for (let i = 0; i < times; i++) { await page.keyboard.press(k); await page.waitForTimeout(110); } };
const state = () => page.evaluate(() => window.KK.G.state);
const autopilot = () => page.evaluate(async () => { const { makeAI } = await import('./js/ai.js?v=1'); const P = window.KK.G.race.player; P.ai = makeAI(0.75); });
await key('Enter'); await key('ArrowDown', 2); await key('Enter'); await page.waitForTimeout(400);
console.log('läge', await state());
await shot('gp-meny');
await key('ArrowRight', 2); await page.waitForTimeout(500); await shot('stall-silver');
await key('ArrowDown'); await key('ArrowRight'); await page.waitForTimeout(300); await shot('forare');
await key('ArrowUp'); await key('ArrowLeft', 2);
await key('ArrowDown', 4); await key('Enter'); await page.waitForTimeout(300); await shot('enstaka');
await key('ArrowDown', 2); await key('ArrowLeft'); await key('ArrowDown', 2); await key('ArrowRight'); await page.waitForTimeout(300); await shot('enstaka-3varv-mjuka');
await key('ArrowDown'); await key('Enter');
await page.waitForFunction(() => window.KK.G.state === 'race', null, { timeout: 60000 });
await page.waitForTimeout(600); await shot('kval-ljus');
await autopilot();
await page.waitForTimeout(6000); await shot('kval-kor');
await key('Escape'); await page.waitForTimeout(300); await shot('kval-paus'); await key('Escape');
await page.waitForFunction(() => window.KK.G.state === 'results', null, { timeout: 120000 });
await page.waitForTimeout(500); await shot('kval-resultat');
console.log('kval:', await page.evaluate(() => { const r = window.KK.G.results; return r.grid.map((c, k) => `${k + 1}.${c.code} ${c.q.toFixed(2)}`).join(' '); }));
await key('Enter');
await page.waitForFunction(() => window.KK.G.state === 'race', null, { timeout: 60000 });
await page.waitForTimeout(1500); await shot('lopp-ljus');
await autopilot();
await page.waitForTimeout(9000); await shot('lopp-kor');
await page.waitForTimeout(9000); await shot('lopp-kor2');
await page.waitForFunction(() => window.KK.G.state === 'results', null, { timeout: 240000 });
await page.waitForTimeout(500); await shot('lopp-resultat');
await key('Enter'); await page.waitForTimeout(800);
console.log('efter loppet:', await state());
await shot('tillbaka-gp');
// säsong
await key('ArrowDown', 3); await key('Enter'); await page.waitForTimeout(300); await shot('ny-sasong');
await key('ArrowDown', 3); await key('Enter'); await page.waitForTimeout(300); await shot('sasong-meny');
await key('ArrowDown', 2); await key('Enter'); await page.waitForTimeout(400); await shot('stallning');
await key('Enter'); await page.waitForTimeout(300);
console.log('efter ställning:', await state(), 'pengar', await page.evaluate(() => window.KK.save.money));
if (errors.length) console.log('FEL:\n' + [...new Set(errors)].join('\n'));
await browser.close();
