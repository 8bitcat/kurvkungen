// Går igenom menyerna med tangentbordet och tar skärmdumpar: node tools/ui.mjs [bredd] [höjd]
import { createRequire } from 'module';
const require = createRequire('D:/Qisy/QISYFrontend/QISYFrontend-1/package.json');
const { chromium } = require('playwright');
const [,, w = '1440', h = '810'] = process.argv;
const PORT = process.env.PORT || '8803';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 3).join('\n')));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(`http://localhost:${PORT}/index.html`);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.KK && window.KK.G.state === 'title', null, { timeout: 60000 });
await page.waitForTimeout(2500);
let n = 0;
const shot = async (name) => { await page.screenshot({ path: `tools/out/ui-${n++}-${name}.png` }); };
const key = async (k, times = 1) => { for (let i = 0; i < times; i++) { await page.keyboard.press(k); await page.waitForTimeout(120); } };
const state = () => page.evaluate(() => window.KK.G.state);
await shot('titel');
await key('Enter'); await page.waitForTimeout(300); await shot('meny');
await key('ArrowDown', 3); await key('Enter'); await page.waitForTimeout(600); await shot('garage');
await key('ArrowRight'); await page.waitForTimeout(400); await shot('garage-komet');
await key('ArrowLeft'); await key('Escape'); await page.waitForTimeout(300);
console.log('efter garaget:', await state());
await key('Enter'); await page.waitForTimeout(300); await shot('cuper');
await key('Enter'); await page.waitForTimeout(300); await shot('fore-lopp');
await key('Enter');
await page.waitForFunction(() => window.KK.G.state === 'race', null, { timeout: 60000 });
await page.waitForTimeout(1500); await shot('nedrakning');
await page.keyboard.down('ArrowUp'); await page.waitForTimeout(4000); await shot('kor');
await page.keyboard.down('Space'); await page.waitForTimeout(800); await shot('skjut'); await page.keyboard.up('Space');
await page.keyboard.down('ShiftLeft'); await page.waitForTimeout(300); await page.keyboard.up('ShiftLeft'); await page.waitForTimeout(500); await shot('nitro');
await page.keyboard.up('ArrowUp');
await key('Escape'); await page.waitForTimeout(300); await shot('paus');
console.log('läge:', await state());
if (errors.length) console.log('FEL:\n' + [...new Set(errors)].join('\n'));
await browser.close();
