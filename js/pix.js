const glyph = (F, ch) => F[ch] || F[ch.toUpperCase()] || (ch === '–' || ch === '—' ? F['-'] : ch === '■' ? F['#'] || F['?'] : F['?']);
export function textW(F, s, scale = 1) {
  let w = 0;
  for (const ch of String(s).toUpperCase()) w += glyph(F, ch).w + 1;
  return Math.max(0, w - 1) * scale;
}
export function eachTextPixel(F, s, x, y, scale, fn) {
  let cx = Math.round(x);
  for (const ch of String(s).toUpperCase()) {
    const G = glyph(F, ch);
    const rows = G.up.length ? [...G.up, ...G.rows] : G.rows, y0 = Math.round(y) - G.up.length * scale;
    for (let j = 0; j < rows.length; j++) {
      const row = rows[j];
      for (let i = 0; i < row.length; i++) if (row[i] === '#') fn(cx + i * scale, y0 + j * scale, j - G.up.length);
    }
    cx += (G.w + 1) * scale;
  }
}
