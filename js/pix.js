// Pixelverktyg (samma grund som Snabbfilens floor-pix.js): färger som heltal 0xRRGGBB,
// stabilt brus (hash), Bayer-dither, ramper (ljus/bas/skugga/djup) och två bitmappstypsnitt.
// Inget här rör document vid import – modulen används även i terrängarbetaren.

export const css = (c) => '#' + (c & 0xffffff).toString(16).padStart(6, '0');
export function mul(c, f) {
  const r = Math.min(255, ((c >> 16) & 255) * f) | 0, g = Math.min(255, ((c >> 8) & 255) * f) | 0, b = Math.min(255, (c & 255) * f) | 0;
  return (r << 16) | (g << 8) | b;
}
export function mix(a, b, t) {
  t = t < 0 ? 0 : t > 1 ? 1 : t;
  const ar = (a >> 16) & 255, ag = (a >> 8) & 255, ab = a & 255;
  return (((ar + (((b >> 16) & 255) - ar) * t) | 0) << 16) | (((ag + (((b >> 8) & 255) - ag) * t) | 0) << 8) | ((ab + ((b & 255) - ab) * t) | 0);
}
export function hash(x, y, s = 0) {
  let n = Math.imul(x | 0, 374761393) + Math.imul(y | 0, 668265263) + Math.imul(s | 0, 2147483647);
  n = Math.imul(n ^ (n >>> 13), 1274126177);
  return ((n ^ (n >>> 16)) >>> 0) / 4294967295;
}
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
export const bayer = (x, y) => (BAYER[((y & 3) << 2) | (x & 3)] + 0.5) / 16;

// Rampen: ljusa toner drar mot varmt vitt, mörka mot blålila.
export const WARM = 0xfff4e0, COOL = 0x2a1f3a, INK = 0x1a1426;
export const ramp = (c) => ({
  hi: mix(mul(c, 1.14), WARM, 0.12),
  base: c,
  lo: mix(mul(c, 0.74), COOL, 0.14),
  dk: mix(mul(c, 0.5), INK, 0.22),
});
// Ljusfaktor k (1 = plan yta i fullt ljus) → färg. Kvantiseras till fasta toner med Bayer-dither.
const SHADE_STEPS = [0.52, 0.66, 0.8, 0.9, 1.0, 1.1, 1.2];
export function shade(c, k, x, y, dith = 0.55) {
  const v = (k - 0.52) / 0.68 * 6 + (bayer(x, y) - 0.5) * dith;
  let i = Math.round(v); i = i < 0 ? 0 : i > 6 ? 6 : i;
  const f = SHADE_STEPS[i];
  if (f >= 1) return mix(mul(c, f), WARM, (f - 1) * 0.9);
  return mix(mul(c, f), COOL, (1 - f) * 0.35);
}
export function jit(c, x, y, s = 0, amt = 0.08) {
  const n = (hash(x, y, s) - 0.5) * amt + (bayer(x, y) - 0.5) * amt * 0.4;
  return n >= 0 ? mix(c, 0xffffff, n) : mix(c, 0, -n);
}
export const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
export const sm = (a, b, v) => { const t = clamp((v - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); };

// ---------- Pennan (bara i huvudtråden) ----------
export class Pix {
  constructor(w, h) {
    this.w = w; this.h = h;
    this.canvas = document.createElement('canvas');
    this.canvas.width = w; this.canvas.height = h;
    this.ctx = this.canvas.getContext('2d');
    this.img = this.ctx.createImageData(w, h);
    this.d = this.img.data;
  }
  px(x, y, c, a = 1) {
    x = Math.floor(x); y = Math.floor(y);
    if (x < 0 || y < 0 || x >= this.w || y >= this.h || a <= 0) return;
    const d = this.d, i = (y * this.w + x) * 4;
    const r = (c >> 16) & 255, g = (c >> 8) & 255, b = c & 255;
    if (a >= 1 || d[i + 3] === 0) { d[i] = r; d[i + 1] = g; d[i + 2] = b; d[i + 3] = a >= 1 ? 255 : a * 255; return; }
    const da = d[i + 3] / 255, oa = a + da * (1 - a), k = da * (1 - a);
    d[i] = (r * a + d[i] * k) / oa; d[i + 1] = (g * a + d[i + 1] * k) / oa; d[i + 2] = (b * a + d[i + 2] * k) / oa; d[i + 3] = oa * 255;
  }
  get(x, y) {
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return -1;
    const i = (y * this.w + x) * 4, d = this.d;
    return d[i + 3] ? (d[i] << 16) | (d[i + 1] << 8) | d[i + 2] : -1;
  }
  alpha(x, y) { return x < 0 || y < 0 || x >= this.w || y >= this.h ? 0 : this.d[(y * this.w + x) * 4 + 3]; }
  rect(x, y, w, h, c, a = 1) { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) this.px(x + i, y + j, c, a); }
  line(x0, y0, x1, y1, c, a = 1) {
    x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
    const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1;
    let e = dx + dy;
    for (;;) {
      this.px(x0, y0, c, a);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * e;
      if (e2 >= dy) { e += dy; x0 += sx; }
      if (e2 <= dx) { e += dx; y0 += sy; }
    }
  }
  ell(cx, cy, rx, ry, c, amax, steps = 4) {
    for (let y = Math.floor(cy - ry); y <= cy + ry; y++) for (let x = Math.floor(cx - rx); x <= cx + rx; x++) {
      const t = Math.hypot((x + 0.5 - cx) / rx, (y + 0.5 - cy) / ry);
      if (t >= 1) continue;
      const v = (1 - t) * steps + bayer(x, y) - 0.5;
      const q = Math.max(0, Math.min(steps, Math.round(v))) / steps;
      if (q > 0) this.px(x, y, c, amax * q);
    }
  }
  // Sel-out-kontur: genomskinlig pixel intill figuren får en mörk, lila ton av grannen.
  outline(strength = 1) {
    const { w, h, d } = this;
    const src = new Uint8ClampedArray(d);
    const order = [[0, -1], [-1, 0], [1, 0], [0, 1]];
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      if (src[i + 3] > 40) continue;
      let best = -1;
      for (const [ox, oy] of order) {
        const xx = x + ox, yy = y + oy;
        if (xx < 0 || yy < 0 || xx >= w || yy >= h) continue;
        const j = (yy * w + xx) * 4;
        if (src[j + 3] > 120) { best = j; break; }
      }
      if (best < 0) continue;
      d[i] = src[best] * 0.28 + 14; d[i + 1] = src[best + 1] * 0.24 + 10; d[i + 2] = src[best + 2] * 0.3 + 22; d[i + 3] = 255 * strength;
    }
  }
  flush() { this.ctx.putImageData(this.img, 0, 0); return this.canvas; }
}

